import math
import sys
from pathlib import Path
import cv2
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paper_plot_style import plt, FIG_DIR
from paper_data import DATA
from escape_ood.suites.layout_gen import TABLE_TOP_Z, project_to_head_cam as P
from escape_ood.suites.spec import ENVELOPE, TRAIN_R, TRAIN_THETA, RADIAL_BAND_R, ANGULAR_BAND_THETA
BG = DATA / 'media/renders/lift_R1_r0.575_th0_head.png'
OUT = FIG_DIR / 'fig0_scene.pdf'
CROP = (40, 632, 0, 352)

def uv(r, th_deg, z=TABLE_TOP_Z):
    t = math.radians(th_deg)
    (u, v, _) = P(r * math.cos(t), r * math.sin(t), z)
    return (u - CROP[0], v - CROP[2])
(RADIAL_C, ANGULAR_C) = ('#b2182b', '#8a8a8a')

def draw(ax, lw=1.0, s_train=4, s_test=7, lw_test=0.6):
    """Draw the cropped head-camera frame with envelope, training and test positions onto ``ax``."""
    img = cv2.cvtColor(cv2.imread(str(BG)), cv2.COLOR_BGR2RGB)[CROP[2]:CROP[3], CROP[0]:CROP[1]]
    (h, w) = img.shape[:2]
    ax.imshow(img)
    e = ENVELOPE
    th = [-e.theta_max_deg + k * 2 * e.theta_max_deg / 60 for k in range(61)]
    ring = [uv(e.r_max, t) for t in th] + [uv(e.r_min, t) for t in reversed(th)]
    ring.append(ring[0])
    ax.plot(*zip(*ring), color='#1f4e9c', lw=lw, ls=(0, (3, 1.5)))
    tr = [uv(r, t) for r in TRAIN_R for t in TRAIN_THETA]
    ax.scatter(*zip(*tr), s=s_train, color='#1f4e9c', lw=0, zorder=3)
    rad = [uv(r, t) for r in RADIAL_BAND_R for t in TRAIN_THETA]
    ang = [uv(r, s * t) for r in TRAIN_R for t in ANGULAR_BAND_THETA for s in (-1, 1)]
    ax.scatter(*zip(*rad), s=s_test, marker='x', color=RADIAL_C, lw=lw_test, zorder=3)
    ax.scatter(*zip(*ang), s=s_test * 0.8, marker='o', facecolors='none', edgecolors=ANGULAR_C, lw=lw_test, zorder=3)
    ax.set_xlim(0, w)
    ax.set_ylim(h, 0)
    return (img, tr, rad, ang)

def main():
    img = cv2.cvtColor(cv2.imread(str(BG)), cv2.COLOR_BGR2RGB)[CROP[2]:CROP[3], CROP[0]:CROP[1]]
    (h, w) = img.shape[:2]
    fig = plt.figure(figsize=(2.6, 2.6 * h / w))
    ax = fig.add_axes([0, 0, 1, 1])
    (img, tr, rad, ang) = draw(ax)
    ax.axis('off')
    fig.savefig(OUT, dpi=300)
    fig.savefig(OUT.with_suffix('.png'), dpi=200)
    (n_tr, n_rad, n_ang) = (len(tr), len(rad), len(ang))
    bands = ', '.join((f'{t:g}^\\circ' for t in ANGULAR_BAND_THETA))
    cap = f"\\textbf{{The policy's view and the region it was trained in.}} Head-camera frame (the policy's input, cropped) with, projected onto the table, the demonstrated envelope $\\env$ (dashed; nothing marks it in the scene), the {n_tr} training positions (dots) and the {n_rad + n_ang} test positions (crosses: {n_rad} radial, 5--25\\,cm beyond $\\env$ at the trained bearings; circles: {n_ang} angular, at $|\\theta| \\in \\{{{bands}\\}}$ and the trained radii). The camera faces the robot, so distance from the base grows down the image and positive $\\theta$ (the robot's left) is on the right. The cube is at the nearest radial test position, 5\\,cm beyond $\\env$ at $\\theta = 0^\\circ$."
    (OUT.parent / 'fig0_scene_include.tex').write_text(f'% Generated by gen_fig0_scene.py\n\\begin{{figure}}[t]\n  \\centering\n  \\includegraphics[width=0.48\\textwidth]{{figures/fig0_scene.pdf}}\n  \\caption{{{cap}}}\n  \\label{{fig:scene}}\n\\end{{figure}}\n')
    print('wrote', OUT)
if __name__ == '__main__':
    main()
