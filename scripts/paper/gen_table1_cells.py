"""Table 1: every manifest cell x three training seeds -- radial episodes reaching approach >= 0.25 and
strict radial successes, per seed (of 70). Validity ranges (training-cell fit, withheld midpoints) are quoted
in the Results text and recorded as a comment in the generated file. Everything is computed from the manifest through the shared metric."""
from pathlib import Path
import paper_data as D
import os
OUT = Path(os.environ.get("ESCAPE_FIGURES_DIR", D.REPO / "outputs/figures"))
OUT.mkdir(parents=True, exist_ok=True)
ROLE_LABEL = {'primary 2x2': '\\multirow{4}{*}{\\rotatebox{90}{\\scriptsize $2{\\times}2$}}', 'rotation control': '\\multirow{3}{*}{\\rotatebox{90}{\\scriptsize controls}}', 'camera panel': '\\multirow{6}{*}{\\rotatebox{90}{\\scriptsize camera}}'}
assert all((c['gripper_command'] == 'absolute' for c in D.MANIFEST['cells'])), 'Table 1 drops the gripper column'
(rows, fit, mid) = ([], [], [])

def tri(v):
    """A seed triple with every count padded to two digits (Times digits are equal width), so the slashes line up."""
    assert all((0 <= x <= 99 for x in v))
    return '\\,/\\,'.join((('\\phantom{0}' if x < 10 else '') + str(x) for x in v))
prev_role = None
GROUP = {'anchor control': 'rotation control'}
for c in D.MANIFEST['cells']:
    runs = list(c['runs'].values())
    esc = [D.stage_counts(r)[1] for r in runs]
    appr = [D.stage_counts(r)[2] for r in runs]
    succ = [D.stage_counts(r)[3] for r in runs]
    fit += [D.split_success(r, 'train') for r in runs]
    mid += [D.split_success(r, 'interior') for r in runs]
    grp = GROUP.get(c['role'], c['role'])
    role = ROLE_LABEL[grp] if grp != prev_role else ''
    if prev_role is not None and grp != prev_role:
        rows.append('\\midrule')
    prev_role = grp
    cams = c['cameras']
    arm = c['arm_command'] + ('$^{\\smash{\\dagger}}$' if c.get('rotation') == 'rotvec' else '') + ('$^{\\smash{\\ddagger}}$' if c.get('anchor') == 'query' else '')
    rows.append(f"{role} & {c['frame']} & {arm} & {cams} & {tri(esc)} & {tri(appr)} & {tri(succ)} \\\\")
fr = f'\\mbox{{{min((a for (a, _) in fit))}--{max((a for (a, _) in fit))}/{fit[0][1]}}}'
mr = f'\\mbox{{{min((a for (a, _) in mid))}--{max((a for (a, _) in mid))}/{mid[0][1]}}}'
tex = f'% Generated by scripts/paper/gen_table1_cells.py from paper_cells.json -- do not edit by hand.\n\\begin{{table}}[!t]\n\\centering\n\\footnotesize\n\\setlength{{\\tabcolsep}}{{4pt}}\n\\begin{{tabular}}{{c l l l c c c}}\n\\toprule\n & frame & arm & cameras & escaped $>$1\\,cm & approach $\\geq$0.25 & strict completion \\\\\n\\midrule\n{chr(10).join(rows)}\n\\bottomrule\n\\end{{tabular}}\n\\caption{{Radial episodes meeting each stage threshold (of 70; training seeds 0\\,/\\,1\\,/\\,2, paired across rows). Each control\nchanges one thing in a $2{{\\times}}2$ cell. $^\\dagger$Orientation as a rotation vector from a fixed top-down $R_0$ (7-d like\nthe EEF residual rows; other absolute EEF rows: position and quaternion, 8-d). $^\\ddagger$Relative to the state at each\nquery. Camera rows (collection B, \\cref{{sec:setup}}) compare only with each other; rows of\none arm command differ only in cameras (a lone wrist image is smaller).}}\n\\label{{tab:cells}}\n\\end{{table}}\n'
tex = tex.replace('\\label{tab:cells}', f'\\label{{tab:cells}}\n% validity (quoted in Results): {len(fit)} runs; strict lifts on the 28 training cells {fr}, on the 21 withheld midpoints {mr}')
(OUT / 'TABLE_cells.tex').write_text(tex)
print(tex)
